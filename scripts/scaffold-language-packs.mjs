const parseRows = (rows, defaultPartOfSpeech) => rows.map((row) => {
  const parts = row.split('|')
  const target = parts[0].trim()
  const origin = parts[1].trim()
  const partOfSpeech = parts.length === 3 ? defaultPartOfSpeech : parts[2].trim()
  const sceneId = parts.length === 3 ? parts[2].trim() : parts[3].trim()
  return { target, origin, partOfSpeech, sceneId }
})

const slugify = (value) => value
  .normalize('NFD')
  .replace(/\p{Diacritic}/gu, '')
  .toLocaleLowerCase()
  .replace(/[^a-z0-9]+/g, '-')
  .replace(/^-|-$/g, '')

const packKind = (packId) => packId.split('-')[0].replace(/s$/, '')

const packRows = Object.entries(rawPacks).flatMap(([packId, rows]) => {
  const defaultPartOfSpeech = packKind(packId)
  const cards = parseRows(rows, defaultPartOfSpeech)
  if (cards.length !== 100) {
    throw new Error(packId + ' has ' + cards.length + ' rows; every source pack must contain exactly 100.')
  }
  return cards.map((card, index) => ({
    ...card,
    id: card.partOfSpeech + '-' + slugify(card.target) + (card.sense && card.sense !== 'primary' ? '-' + slugify(card.sense) : ''),
    packId,
    packIndex: index + 1,
  }))
})

const expectedCardCount = Object.values(rawPacks).reduce((total, rows) => total + rows.length, 0)
if (packRows.length !== expectedCardCount) {
  throw new Error('Expected ' + expectedCardCount + ' scaffold cards; found ' + packRows.length + '.')
}

const duplicateIds = packRows.filter((card, index) => packRows.findIndex((candidate) => candidate.id === card.id) !== index)
if (duplicateIds.length > 0) {
  throw new Error('Duplicate generated ids: ' + [...new Set(duplicateIds.map((card) => card.id))].join(', '))
}

const sceneById = new Map(sceneDefinitions.map((scene) => [scene.id, scene]))
for (const card of packRows) {
  if (!sceneById.has(card.sceneId)) {
    throw new Error('Unknown scene ' + card.sceneId + ' for ' + card.target)
  }
}

await fs.mkdir(packRoot, { recursive: true })
await fs.mkdir(sourceRoot, { recursive: true })

for (const [packId] of Object.entries(rawPacks)) {
  const folder = packId.split('-')[0]
  const shard = packId.split('-')[1]
  const words = packRows
    .filter((card) => card.packId === packId)
    .map(({ id, target, origin, partOfSpeech, sense }) => {
      const word = { target, origin }
      const canonicalId = partOfSpeech + '-' + slugify(target) + (sense && sense !== 'primary' ? '-' + slugify(sense) : '')
      if (id !== canonicalId) word.id = id
      if (sense && sense !== 'primary') word.sense = sense
      if (packKind(packId) === 'function') word.partOfSpeech = partOfSpeech
      return word
    })
  const output = { words }
  const folderPath = path.join(sourceRoot, folder)
  await fs.mkdir(folderPath, { recursive: true })
  await fs.writeFile(
    path.join(folderPath, shard + '.json'),
    JSON.stringify(output, null, 2) + '\n',
    'utf8',
  )
}

